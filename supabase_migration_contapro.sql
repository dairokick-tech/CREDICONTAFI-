create extension if not exists pgcrypto;

create table if not exists public.contapro_companies (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  tax_id text,
  status text not null default 'Activo',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.contapro_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'user' check (role in ('superadmin','admin','user')),
  company_id uuid references public.contapro_companies(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.contapro_clients (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.contapro_companies(id) on delete cascade,
  name text not null,
  document text,
  balance numeric(14,2) not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.contapro_suppliers (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.contapro_companies(id) on delete cascade,
  name text not null,
  document text,
  phone text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.contapro_sales (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.contapro_companies(id) on delete cascade,
  document_no text not null,
  client_name text,
  amount numeric(14,2) not null default 0,
  date date not null default current_date,
  status text not null default 'Registrada',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.contapro_purchases (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.contapro_companies(id) on delete cascade,
  document_no text not null,
  supplier_name text,
  amount numeric(14,2) not null default 0,
  date date not null default current_date,
  status text not null default 'Registrada',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.contapro_audit_log (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  action text not null,
  table_name text not null,
  record_id text,
  detail jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_contapro_clients_company on public.contapro_clients(company_id);
create index if not exists idx_contapro_suppliers_company on public.contapro_suppliers(company_id);
create index if not exists idx_contapro_sales_company_date on public.contapro_sales(company_id,date);
create index if not exists idx_contapro_purchases_company_date on public.contapro_purchases(company_id,date);
create index if not exists idx_contapro_profiles_company on public.contapro_profiles(company_id);

