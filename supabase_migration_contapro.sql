-- Funciones de autorización. No modifican ni eliminan datos de negocio.
create or replace function public.contapro_is_superadmin()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.contapro_profiles p where p.id=auth.uid() and p.role='superadmin'); $$;

create or replace function public.contapro_my_company()
returns uuid language sql stable security definer set search_path=public
as $$ select company_id from public.contapro_profiles where id=auth.uid(); $$;

-- Policies: se eliminan SOLO policies con estos nombres para poder re-ejecutar
-- la migración; las tablas y sus datos NO se eliminan.
drop policy if exists contapro_companies_select on public.contapro_companies;
drop policy if exists contapro_companies_write on public.contapro_companies;
create policy contapro_companies_select on public.contapro_companies for select to authenticated
using (public.contapro_is_superadmin() or id=public.contapro_my_company());
create policy contapro_companies_write on public.contapro_companies for all to authenticated
using (public.contapro_is_superadmin()) with check (public.contapro_is_superadmin());

drop policy if exists contapro_profiles_select on public.contapro_profiles;
drop policy if exists contapro_profiles_write on public.contapro_profiles;
create policy contapro_profiles_select on public.contapro_profiles for select to authenticated
using (id=auth.uid() or public.contapro_is_superadmin());
create policy contapro_profiles_write on public.contapro_profiles for all to authenticated
using (public.contapro_is_superadmin()) with check (public.contapro_is_superadmin());

drop policy if exists contapro_clients_access on public.contapro_clients;
create policy contapro_clients_access on public.contapro_clients for all to authenticated
using (public.contapro_is_superadmin() or company_id=public.contapro_my_company())
